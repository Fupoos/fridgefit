const round = (v) => Math.round(v * 100) / 100

/** Canned foods whose nutrition is per drained weight; drained weight ≈ 60% of net (approximation, see DATA_SOURCES.md). */
const CANNED = new Set(['tuna_can', 'lentils_can', 'chickpeas_can', 'black_beans_can'])
const DRAINED_FRACTION = 0.6

const ids = read('food_ids.json')
const fdc = new Map(read('foods_fdc.json').map((f) => [f.id, f]))
const foods = ids.map((f) => {
  const src = fdc.get(f.id)
  if (!src?.per100g || src.per100g.kcal == null) throw new Error(`Missing FDC values for ${f.id}`)
  const m = src.per100g
  return {
    id: f.id,
    name: NAMES[f.id] ?? f.name,
    category: f.category,
    ultraProcessed: f.ultraProcessed,
    portionG: f.portionG,
    per100g: { kcal: round(m.kcal), protein: round(m.protein), fat: round(m.fat), carbs: round(m.carbs) },
    tags: TAGS[f.id] ?? [],
    fdcId: src.fdcId,
  }
})

const header = (what) =>
  `// GENERATED by scripts/build-data.mjs — do not edit by hand.\n// ${what}\n`

writeFileSync(
  join(root, 'src', 'data', 'foods.ts'),
  `${header('Per-100 g values from USDA FoodData Central (public domain, CC0); see DATA_SOURCES.md.')}import type { Food } from '../types'

export const FOODS: Food[] = ${JSON.stringify(foods, null, 2)}

export const FOOD_MAP = new Map(FOODS.map((f) => [f.id, f]))
`,
)
console.log(`foods.ts: ${foods.length} foods`)

if (existsSync(join(working, 'qld_grocery.json'))) {
  const g = read('qld_grocery.json')
  const valid = new Set(foods.map((f) => f.id))
  const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
  const seen = new Set()
  const products = g.products
    .filter((p) => valid.has(p.foodId) && p.packGrams > 0)
    .map((p) => {
      let id = slug(`${p.store}-${p.productName}`)
      while (seen.has(id)) id += '-x'
      seen.add(id)
      return {
        id,
        foodId: p.foodId,
        store: p.store,
        productName: p.productName,
        packSize: p.packSize,
        // Can labels give net weight including liquid; FDC values are for drained food.
        packGrams: CANNED.has(p.foodId) ? Math.round(p.packGrams * DRAINED_FRACTION) : p.packGrams,
        priceAUD: typeof p.priceAUD === 'number' ? p.priceAUD : null,
        unitPriceText: p.unitPriceText ?? '',
        url: p.url ?? '',
        checkedOn: p.checkedOn ?? g.checkedOn,
      }
    })
  const seasonal = g.seasonalOctoberSEQ ?? null
  writeFileSync(
    join(root, 'src', 'data', 'qldGrocery.ts'),
    `${header('Online shelf prices from Woolworths, Coles and ALDI Australia; see DATA_SOURCES.md.')}import type { GroceryProduct } from '../types'

export const PRICES_CHECKED_ON = ${JSON.stringify(g.checkedOn)}

export const PRICE_NOTE = ${JSON.stringify(g.note)}

export const QLD_CATALOG: GroceryProduct[] = ${JSON.stringify(products, null, 2)}

/** Produce in season in South-East Queensland in October (null if not verified). */
export const SEASONAL_SEQ: { foodIds: string[]; source: string } | null = ${JSON.stringify(seasonal, null, 2)}
`,
  )
  const priced = products.filter((p) => p.priceAUD !== null).length
  console.log(`qldGrocery.ts: ${products.length} products (${priced} priced)`)
} else {
  console.log('qld_grocery.json not found yet — skipped qldGrocery.ts')
}
