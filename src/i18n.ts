export const DICT = { en, zh } as const

export type Vars = Record<string, string | number>

export function translate(lang: Lang, key: Key, vars?: Vars): string {
  const s: string = DICT[lang][key] ?? DICT.en[key] ?? key
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s
}

export function detectLang(): Lang {
  try {
    return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
  } catch {
    return 'en'
  }
}

export function foodName(id: string, lang: Lang): string {
  return lang === 'zh' ? (FOOD_NAMES_ZH[id] ?? FOOD_MAP.get(id)?.name ?? id) : (FOOD_MAP.get(id)?.name ?? id)
}

/** Joins a short list the way each language does ("a, b and c" / "a、b和c"). */
export function joinList(items: string[], lang: Lang): string {
  if (items.length <= 1) return items.join('')
  const comma = translate(lang, 'join.comma')
  return `${items.slice(0, -1).join(comma)}${translate(lang, 'join.and')}${items[items.length - 1]}`
}

export interface I18n {
  lang: Lang
  t: (key: Key, vars?: Vars) => string
  food: (id: string) => string
  locale: string
}

export function makeI18n(lang: Lang): I18n {
  return {
    lang,
    t: (key, vars) => translate(lang, key, vars),
    food: (id) => foodName(id, lang),
    locale: lang === 'zh' ? 'zh-CN' : 'en-AU',
  }
}

export const I18nContext = createContext<I18n>(makeI18n('en'))

export const useI18n = () => useContext(I18nContext)
